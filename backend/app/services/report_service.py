"""
app/services/report_service.py
────────────────────────────────
Compliance report generation + storage.

LOCAL mode (S3_BUCKET_NAME not set):
  Saves PDF to ./storage/reports/<investigation_id>.pdf
  Returns a local file:// URL.

PRODUCTION mode (S3_BUCKET_NAME set):
  Uploads to Amazon S3, returns a presigned URL (valid 1 hour) or
  public URL if the bucket policy permits.
"""
from __future__ import annotations

import logging
from datetime import datetime, timezone
from io import BytesIO
from pathlib import Path
from typing import Optional

from app.core.config import settings

logger = logging.getLogger(__name__)

_s3_client = None


def _get_s3():
    global _s3_client
    if _s3_client is None:
        import boto3
        kwargs = {"region_name": settings.AWS_REGION}
        if settings.AWS_ACCESS_KEY_ID:
            kwargs["aws_access_key_id"] = settings.AWS_ACCESS_KEY_ID
            kwargs["aws_secret_access_key"] = settings.AWS_SECRET_ACCESS_KEY
        _s3_client = boto3.client("s3", **kwargs)
    return _s3_client


def generate_pdf_report(
    investigation_id: int,
    alerts: list,
    notes: str,
    opened_by: str,
) -> bytes:
    """Generate a PDF compliance report and return raw bytes."""
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4)
    styles = getSampleStyleSheet()
    story = []

    # Title
    story.append(Paragraph("Market Surveillance — Compliance Investigation Report", styles["Title"]))
    story.append(Spacer(1, 12))
    story.append(Paragraph(f"Investigation ID: #{investigation_id}", styles["Heading2"]))
    story.append(Paragraph(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", styles["Normal"]))
    story.append(Paragraph(f"Opened by: {opened_by}", styles["Normal"]))
    story.append(Spacer(1, 12))

    if notes:
        story.append(Paragraph("Analyst Notes", styles["Heading2"]))
        story.append(Paragraph(notes, styles["Normal"]))
        story.append(Spacer(1, 12))

    # Alerts table
    story.append(Paragraph("Flagged Alerts", styles["Heading2"]))
    if alerts:
        table_data = [["Alert ID", "Trade", "Trader", "Symbol", "Risk", "Z-Score", "Score"]]
        for a in alerts:
            trade = a.trade
            table_data.append([
                str(a.id),
                trade.trade_code if trade else "-",
                trade.trader_id if trade else "-",
                trade.symbol if trade else "-",
                a.risk_level,
                f"{a.notional_zscore:+.2f}" if a.notional_zscore else "-",
                f"{a.combined_score:.3f}" if a.combined_score else "-",
            ])
        t = Table(table_data, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), (0.2, 0.2, 0.2)),
            ("TEXTCOLOR", (0, 0), (-1, 0), (1, 1, 1)),
            ("GRID", (0, 0), (-1, -1), 0.5, (0.5, 0.5, 0.5)),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [(0.95, 0.95, 0.95), (1, 1, 1)]),
        ]))
        story.append(t)
    else:
        story.append(Paragraph("No alerts linked to this investigation.", styles["Normal"]))

    story.append(Spacer(1, 20))
    story.append(Paragraph(
        "DISCLAIMER: This report is generated by an academic prototype using "
        "synthetic data only. It does not constitute evidence of regulatory violations "
        "or proven insider trading. All findings require human review.",
        styles["Italic"],
    ))

    doc.build(story)
    return buf.getvalue()


def save_report(
    investigation_id: int,
    pdf_bytes: bytes,
) -> tuple[str, str]:
    """
    Save PDF to S3 (prod) or local disk (local).
    Returns (s3_key, url).
    """
    filename = f"investigation_{investigation_id}_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}.pdf"

    if settings.use_s3:
        s3 = _get_s3()
        key = f"reports/{filename}"
        try:
            s3.put_object(
                Bucket=settings.S3_BUCKET_NAME,
                Key=key,
                Body=pdf_bytes,
                ContentType="application/pdf",
            )
            url = s3.generate_presigned_url(
                "get_object",
                Params={"Bucket": settings.S3_BUCKET_NAME, "Key": key},
                ExpiresIn=3600,
            )
            logger.info("Report uploaded to s3://%s/%s", settings.S3_BUCKET_NAME, key)
            return key, url
        except Exception as exc:
            logger.error("S3 upload failed: %s — saving locally", exc)

    # Local fallback
    local_dir = Path(settings.LOCAL_STORAGE_DIR)
    local_dir.mkdir(parents=True, exist_ok=True)
    local_path = local_dir / filename
    local_path.write_bytes(pdf_bytes)
    logger.info("Report saved locally to %s", local_path)
    return str(local_path), f"file://{local_path.resolve()}"
