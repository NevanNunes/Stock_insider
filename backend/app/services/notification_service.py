"""
app/services/notification_service.py
──────────────────────────────────────
HIGH-risk alert notifications.

LOCAL mode (SNS_TOPIC_ARN not set):
  Logs the alert to console in a clearly formatted block.
  Also writes a mock notification to ./storage/notifications/<trade_code>.txt
  so you can see exactly what the SNS email would contain.

PRODUCTION mode (SNS_TOPIC_ARN set):
  Publishes to Amazon SNS (email/phone delivery to subscribed team members).
"""
from __future__ import annotations

import logging
import os
from pathlib import Path

from app.core.config import settings

logger = logging.getLogger(__name__)

_sns_client = None


def _get_sns():
    global _sns_client
    if _sns_client is None:
        import boto3
        kwargs = {"region_name": settings.AWS_REGION}
        if settings.AWS_ACCESS_KEY_ID:
            kwargs["aws_access_key_id"] = settings.AWS_ACCESS_KEY_ID
            kwargs["aws_secret_access_key"] = settings.AWS_SECRET_ACCESS_KEY
        _sns_client = boto3.client("sns", **kwargs)
    return _sns_client


def _build_sns_message(trade_code: str, trader_id: str, symbol: str,
                        risk_level: str, combined_score: float,
                        notional_z: float, reason: str) -> tuple[str, str]:
    """Returns (subject, body) for the SNS notification."""
    subject = f"🚨 CRITICAL ALERT: {risk_level} Risk Trade Detected — {trader_id} / {symbol}"
    body = f"""
=== MARKET SURVEILLANCE ALERT ===
Unusual trading activity detected. Further human review recommended.

Risk Level   : {risk_level}
Anomaly Score: {combined_score:.3f} / 1.000
Trade Code   : {trade_code}
Trader       : {trader_id}
Symbol       : {symbol}
Z-Score      : {notional_z:+.2f}σ

Reason:
{reason}

Note: This is a statistical anomaly flag generated by an academic prototype
using synthetic data only. It does not constitute evidence of wrongdoing.

Login to the Surveillance Dashboard to investigate this alert.
===================================
""".strip()
    return subject, body


def notify_high_risk_alert(
    trade_code: str,
    trader_id: str,
    symbol: str,
    risk_level: str,
    combined_score: float,
    notional_z: float,
    reason: str,
) -> None:
    """
    Send alert notification for a HIGH-risk trade.
    Call this only when risk_level == "HIGH".
    """
    subject, body = _build_sns_message(
        trade_code, trader_id, symbol, risk_level, combined_score, notional_z, reason
    )

    if settings.use_sns:
        try:
            sns = _get_sns()
            sns.publish(
                TopicArn=settings.SNS_TOPIC_ARN,
                Subject=subject[:100],  # SNS subject limit
                Message=body,
            )
            logger.info("SNS notification sent for trade %s", trade_code)
        except Exception as exc:
            logger.error("SNS publish failed: %s", exc)
            _save_local_notification(trade_code, subject, body)
    else:
        # Local fallback — print + save file
        logger.warning("\n%s\n%s\n%s", "=" * 60, body, "=" * 60)
        _save_local_notification(trade_code, subject, body)


def _save_local_notification(trade_code: str, subject: str, body: str) -> None:
    """Save the notification to a local file as a mock SNS email."""
    notif_dir = Path(settings.LOCAL_STORAGE_DIR).parent / "notifications"
    notif_dir.mkdir(parents=True, exist_ok=True)
    path = notif_dir / f"{trade_code}.txt"
    path.write_text(f"SUBJECT: {subject}\n\n{body}\n", encoding="utf-8")
    logger.info("Local SNS mock saved to %s", path)
